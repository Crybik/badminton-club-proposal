import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
const output = resolve(process.argv[2] || '.checks');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
const base = process.env.BASE_URL || 'http://127.0.0.1:3000';
await page.goto(`${base}/?lang=en`);
await page.screenshot({ path: resolve(output, 'proposal-desktop.png') });
await page.locator('#experience').scrollIntoViewIfNeeded();
await page.screenshot({ path: resolve(output, 'proposal-experience.png') });
await page.setViewportSize({ width: 390, height: 1000 });
await page.goto(`${base}/?lang=ar`);
await page.screenshot({ path: resolve(output, 'proposal-arabic-mobile.png') });
await page.emulateMedia({ media: 'print' });
await page.pdf({ path: resolve(output, 'proposal-arabic.pdf'), format: 'A4', printBackground: true, preferCSSPageSize: true });
await browser.close();
console.log(`Screenshots and PDF saved to ${output}`);
